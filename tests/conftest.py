def call(name: str, args: dict[str, Any], session: str | None = "session-1") -> dict[str, Any]:
    raw = HANDLERS[name](args, session_id=session, task_id="task-1")
    assert isinstance(raw, str)
    return json.loads(raw)


def assert_refused_unchanged(name: str, args: dict[str, Any], path: Path, *, reason: str | None = None, session: str | None = "session-1") -> dict[str, Any]:
    before = sha256(path)
    out = call(name, args, session)
    assert out["ok"] is False, out
    if reason is not None:
        assert out["reason"] == reason, out
    assert sha256(path) == before, "a refused edit must leave the file byte-identical"
    return out
